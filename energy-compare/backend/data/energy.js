function getSortedByLCOE() {
  return [...SOURCES].sort((a, b) => a.lcoe.avg - b.lcoe.avg);
}

function getSortedByCO2() {
  return [...SOURCES].sort((a, b) => a.co2 - b.co2);
}

function getStats() {
  const sorted = getSortedByLCOE();
  return {
    cheapest: sorted[0],
    mostExpensive: sorted[sorted.length - 1],
    cleanest: [...SOURCES].sort((a, b) => a.co2 - b.co2)[0],
    mostReliable: [...SOURCES].sort((a, b) => b.capacityFactor - a.capacityFactor)[0],
    avgLCOE: Math.round(SOURCES.reduce((s, x) => s + x.lcoe.avg, 0) / SOURCES.length),
  };
}

